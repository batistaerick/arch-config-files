def parse_colors(path: Path) -> dict[str, str]:
    data: dict[str, str] = {}
    pattern = re.compile(r'^\s*([A-Za-z0-9_]+)\s*=\s*"?(#[0-9A-Fa-f]{6})"?')
    for line in path.read_text().splitlines():
        match = pattern.match(line)
        if match:
            data[match.group(1)] = match.group(2).lower()
    return data


def hex_to_rgb(value: str) -> tuple[int, int, int]:
    value = value.lstrip("#")
    return tuple(int(value[i : i + 2], 16) for i in (0, 2, 4))


def rgb_to_hex(rgb: tuple[int, int, int]) -> str:
    return "#{:02x}{:02x}{:02x}".format(*rgb)


def rgba(color: str, alpha: str) -> str:
    red, green, blue = hex_to_rgb(color)
    return f"rgba({red}, {green}, {blue}, {alpha})"


def mix(left: str, right: str, amount: float) -> str:
    l_rgb = hex_to_rgb(left)
    r_rgb = hex_to_rgb(right)
    return rgb_to_hex(
        tuple(round(l_rgb[i] * (1 - amount) + r_rgb[i] * amount) for i in range(3))
    )


def luminance(color: str) -> float:
    rgb = [channel / 255 for channel in hex_to_rgb(color)]
    linear = [
        channel / 12.92
        if channel <= 0.04045
        else ((channel + 0.055) / 1.055) ** 2.4
        for channel in rgb
    ]
    return 0.2126 * linear[0] + 0.7152 * linear[1] + 0.0722 * linear[2]


def require(colors: dict[str, str], key: str) -> str:
    if key not in colors:
        raise SystemExit(f"Missing {key} in colors file")
    return colors[key]


