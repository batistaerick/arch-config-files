def main() -> int:
    if len(sys.argv) != 3:
        print("Usage: generate-theme.py <colors.toml> <output.css>", file=sys.stderr)
        return 2

    colors_path = Path(sys.argv[1]).expanduser()
    output_path = Path(sys.argv[2]).expanduser()
    colors = parse_colors(colors_path)

    if output_path.is_symlink():
        output_path.unlink()

    output_path.write_text(build_css(colors))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
